#!/usr/bin/env python3
"""Concatenate src/pNN_*.py into one pygame release.

version.json is the only version string. It names the output file and is
embedded once, before the modules, so the title and the filename match.
maps/world.json and maps/vellamo.json are embedded. The game does not read
them at runtime.
"""
import json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "src")
version = json.load(open(os.path.join(HERE, "version.json"), encoding="utf-8"))["version"]
if not re.match(r"\d+\.\d+\.\d+$", version):
    sys.exit("version.json must be a plain x.y.z string")
OUT = os.path.join(HERE, "TuonelanPolku%s.pygame" % version) if len(sys.argv) < 2 else sys.argv[1]
parts = sorted(
    (f for f in os.listdir(SRC) if re.match(r"p\d+_.*\.py$", f)),
    key=lambda f: int(re.match(r"p(\d+)_", f).group(1)),
)
if parts[-1] != "p99_entry.py":
    sys.exit("p99_entry.py must be the last module")
world = json.load(open(os.path.join(HERE, "maps", "world.json"), encoding="utf-8"))
vellamo = json.load(open(os.path.join(HERE, "maps", "vellamo.json"), encoding="utf-8"))
stamp = 'VERSION = "%s"\n' % version
with open(OUT, "w", encoding="utf-8") as out:
    out.write("# Built by TuonelanPolku/build.py from version.json %s. Do not edit this file by hand.\n" % version)
    out.write(stamp)
    for name in parts:
        if name == "p3_world.py":
            out.write("\n# ======== maps/world.json ========\nWORLD_LAYOUT = ")
            out.write(repr(world))
            out.write("\n")
        if name == "p16_vellamo_core.py":
            out.write("\n# ======== maps/vellamo.json ========\nVELLAMO_LAYOUT = ")
            out.write(repr(vellamo))
            out.write("\n")
        body = open(os.path.join(SRC, name), encoding="utf-8").read()
        if re.search(r"^VERSION\s*=", body, re.M):
            sys.exit("%s assigns VERSION; version.json is the only source" % name)
        out.write("\n# ======== %s ========\n" % name)
        out.write(body)
        if not body.endswith("\n"):
            out.write("\n")
text = open(OUT, encoding="utf-8").read()
if text.count('if __name__ == "__main__":') != 1:
    sys.exit("release must contain exactly one entrypoint")
if text.count(stamp.strip()) != 1:
    sys.exit("VERSION must be embedded exactly once")
print("built", OUT, len(parts), "parts", os.path.getsize(OUT), "bytes")
