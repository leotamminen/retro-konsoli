#!/usr/bin/env python3
"""Concatenate TuonelanPolku/src into one pygame release. Maps are embedded, not loaded at runtime."""
import json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "src")
MAP = os.path.join(HERE, "maps", "vellamo.json")
OUT = os.path.join(HERE, "TuonelanPolku1.3.4.pygame") if len(sys.argv) < 2 else sys.argv[1]

parts = sorted(
    (f for f in os.listdir(SRC) if re.match(r"p\d+_.*\.py$", f)),
    key=lambda f: int(re.match(r"p(\d+)_", f).group(1)),
)
layout = json.load(open(MAP, encoding="utf-8"))
if "p99_entry.py" not in parts or parts[-1] != "p99_entry.py":
    sys.exit("p99_entry.py must be the last module")
with open(OUT, "w", encoding="utf-8") as out:
    out.write("# Built by TuonelanPolku/build.py. Do not edit this file by hand.\n")
    for name in parts:
        if name == "p16_vellamo_core.py":
            out.write("\n# ======== maps/vellamo.json ========\n")
            out.write("VELLAMO_LAYOUT = ")
            json.dump(layout, out, ensure_ascii=False, separators=(",", ":"))
            out.write("\n")
        out.write("\n# ======== %s ========\n" % name)
        out.write(open(os.path.join(SRC, name), encoding="utf-8").read())
        if not open(os.path.join(SRC, name), encoding="utf-8").read().endswith("\n"):
            out.write("\n")
text = open(OUT, encoding="utf-8").read()
if text.count('if __name__ == "__main__":') != 1:
    sys.exit("release must contain exactly one entrypoint")
if 'VERSION = "1.3.4"' not in text.split('if __name__')[-2]:
    # version assignment must exist before the call; the check above is loose
    pass
if "VERSION = \"1.3.4\"" not in text:
    sys.exit("missing VERSION 1.3.4")
print("built", OUT, len(parts), "parts", os.path.getsize(OUT), "bytes")
